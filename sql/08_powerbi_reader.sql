-- Read-only user for the Power BI connection. Signs in with a programmatic access token
-- (PAT) used as the password, restricted to ENGINE_ANALYST. Run as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

CREATE USER IF NOT EXISTS POWERBI_READER
  TYPE = SERVICE
  DEFAULT_ROLE = ENGINE_ANALYST
  DEFAULT_WAREHOUSE = ENGINE_WH
  COMMENT = 'Power BI connection (read only)';
GRANT ROLE ENGINE_ANALYST TO USER POWERBI_READER;

-- PATs need a network policy by default; this policy allows the token without one
CREATE AUTHENTICATION POLICY IF NOT EXISTS ENGINE_ANALYTICS.ANALYTICS.AP_POWERBI_PAT
  AUTHENTICATION_METHODS = ('PROGRAMMATIC_ACCESS_TOKEN')
  PAT_POLICY = (NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED);
ALTER USER POWERBI_READER SET AUTHENTICATION POLICY ENGINE_ANALYTICS.ANALYTICS.AP_POWERBI_PAT;

